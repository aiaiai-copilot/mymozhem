// Вуаль нефокусного окна (находка Н1, решение 1): чисто визуальный слой БЕЗ
// перехвата кликов (pointer-events: none в .focus-dim) — на macOS ОС съедает
// первый клик на активацию окна раньше страницы, на Windows click-through
// доставляет клик контенту; щит съедал бы рабочие клики, вуаль нигде не
// мешает и везде объясняет. Текст — черновик дизайна §4, финальная редакция
// на живой приёмке. aria-hidden: слой декоративный, состояние фокуса окна
// скринридеру недоступно и не действие.
export function FocusDim() {
  return (
    <div className="focus-dim" aria-hidden="true">
      <p className="focus-dim-text">Окно неактивно — кликните, чтобы продолжить</p>
    </div>
  );
}
