import { describe, expect, it } from 'vitest';
import { HOST_CONSOLE_PATH, HOST_NEW_PATH } from './routes';

// Пин маршрутов с несколькими потребителями (находка A приёмки 2026-10-14):
// ссылка экрана «комната не найдена» вела на /host/setup → 404, потому что
// путь был зашит строкой в двух местах (роутер и ссылка) и разъехался. Теперь
// все стороны импортируют константы — дрейф невозможен структурно; спека
// пинит сами wire-значения: смена маршрута — сознательный акт с правкой
// этого теста. '/' осознанно остаётся литералом: корень зарегистрирован
// всегда, класс 404 для него недостижим.
describe('routes', () => {
  it('HOST_NEW_PATH — зарегистрированный маршрут setup-страницы', () => {
    expect(HOST_NEW_PATH).toBe('/host/new');
  });

  it('HOST_CONSOLE_PATH — зарегистрированный маршрут консоли ведущего', () => {
    expect(HOST_CONSOLE_PATH).toBe('/host/console');
  });
});
