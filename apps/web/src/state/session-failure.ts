import { ApiError } from '../api/api-error';

// Классификация отказов сессии — единая точка решения «сеть ≠ отказ сервера»
// (дизайн §3(В), принцип решения 4: сетевой обрыв любой длины НЕ убивает
// сессию; смерть — только по слову сервера). Потребители: connect_error в
// RoomConnection (T4), rejoin гостя на play (T5).
//
// Таблица (план I-1: предикат обобщён до ApiError 4xx — покрывает и refresh-401
// (буква §3(В)), и join-отказы 403/404/409 одним правилом):
//   ApiError 4xx (401 refresh, 403/404/409 join)  → ТЕРМИНАЛ: сервер отказал
//     по существу — refresh-кука протухла/отозвана, комната терминальна.
//   ApiError 5xx (HTTP_502 и т.п.)                → временный: инфраструктурный
//     обрыв (рестарт/редеплой посреди события), сервер сессию не судил;
//     терминальность 5xx убивала бы все гостевые сессии разом при рестарте.
//   ApiError статус 0 (PUBLISH_TIMEOUT и др.)     → временный: wire-уровень,
//     серверного ответа не было вовсе.
//   TypeError (fetch: сеть лежит), AbortError (таймаут FETCH_TIMEOUT_MS),
//   неизвестное                                   → временный: пауза, retry —
//     по wake-каналу (online/пробуждение), личность не трогаем.
export function isTerminalSessionFailure(e: unknown): boolean {
  return e instanceof ApiError && e.status >= 400 && e.status < 500;
}
